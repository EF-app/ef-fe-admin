export interface MockPostItPage {
  content: PostItBe[];
  page: number;
  size: number;
  totalElements: number;
  totalPages: number;
  last: boolean;
}

export function buildMockPostItBePage(
  params: {
    page?: number;
    size?: number;
    keyword?: string;
    categoryCode?: string;
    isHidden?: boolean;
    isDeleted?: boolean;
  } = {}
): MockPostItPage {
  const size = params.size ?? 12;
  const page = params.page ?? 0;
  let filtered = mockPostItsBe;
  if (params.categoryCode) {
    filtered = filtered.filter((p) => p.categoryCode === params.categoryCode);
  }
  if (params.isHidden !== undefined) {
    filtered = filtered.filter((p) => p.hidden === params.isHidden);
  }
  if (params.isDeleted !== undefined) {
    filtered = filtered.filter((p) => p.deleted === params.isDeleted);
  }
  if (params.keyword) {
    const kw = params.keyword.toLowerCase();
    filtered = filtered.filter(
      (p) =>
        p.content.toLowerCase().includes(kw) ||
        p.userNickname.toLowerCase().includes(kw)
    );
  }
  const totalElements = filtered.length;
  const totalPages = Math.max(1, Math.ceil(totalElements / size));
  const start = page * size;
  return {
    content: filtered.slice(start, start + size),
    page,
    size,
    totalElements,
    totalPages,
    last: page + 1 >= totalPages,
  };
}

export const mockPostItsBePage = buildMockPostItBePage();
